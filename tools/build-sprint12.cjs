const fs = require('fs');
const path = require('path');

const manifest = JSON.parse(fs.readFileSync('src/config/sprint12.manifest.json', 'utf8'));
const read = file => fs.readFileSync(file, 'utf8');
const banner = label => `/* ${label} — generated by tools/build-sprint12.cjs */\n`;

function replaceRequired(source, search, replacement, label) {
  if (!source.includes(search)) throw new Error(`Build guard failed: ${label}`);
  return source.replace(search, replacement);
}

const css = manifest.css.map(file => `${banner(file)}${read(file).trim()}\n`).join('\n');
fs.writeFileSync('sprint12.bundle.css', `${banner('S.A.G. Frontier consolidated styles')}${css}`);

const ui = manifest.ui.map(file => `${banner(file)}${read(file).trim()}\n`).join('\n');
fs.writeFileSync('sprint12-ui.js', `${banner('S.A.G. Frontier consolidated UI modules')}${ui}`);
fs.copyFileSync(manifest.balance, 'sprint12-config.js');

let runtime = read(manifest.runtime);
runtime = replaceRequired(runtime, "(()=>{'use strict';", "(()=>{'use strict';\nconst CONFIG=window.SAG12_CONFIG;if(!CONFIG)throw new Error('SAG12_CONFIG missing');", 'runtime config bootstrap');
runtime = replaceRequired(runtime, "version:11,language:'de'", "version:CONFIG.version,language:'de'", 'save version');
runtime = replaceRequired(runtime, "out.version=11;return out", "out.version=CONFIG.version;return out", 'normalized version');
runtime = runtime.replaceAll('S.A.G. FRONTIER // DEEP SPACE REFINED 0.11', 'S.A.G. FRONTIER // MODULAR DEEP SPACE 0.12');
runtime = replaceRequired(runtime, "const CHUNK_SIZE=900,WORLD_RADIUS=2,CHUNK_CACHE_LIMIT=180", "const CHUNK_SIZE=CONFIG.world.chunkSize,WORLD_RADIUS=CONFIG.world.activeRadius,CHUNK_CACHE_LIMIT=CONFIG.world.cacheLimit", 'world constants');
runtime = replaceRequired(runtime, "Math.hypot(x,y)<285", "Math.hypot(x,y)<CONFIG.world.safeOriginRadius", 'origin safe radius');
runtime = replaceRequired(runtime, "rnd()<.1", "rnd()<CONFIG.world.stationChance", 'station chance');
runtime = replaceRequired(runtime, "Math.hypot(x,y)>=340", "Math.hypot(x,y)>=CONFIG.world.stationSafeRadius", 'station safe radius');
runtime = replaceRequired(runtime, "spawnGrace:3.5", "spawnGrace:CONFIG.timing.spawnGrace", 'spawn grace');
runtime = replaceRequired(runtime, "maxEnemies:save.difficulty==='veteran'?44:save.difficulty==='operation'?36:28", "maxEnemies:CONFIG.enemyLimits[save.difficulty]", 'enemy limits');
runtime = replaceRequired(runtime, "hudClock=.1;updateHUD()", "hudClock=CONFIG.performance.hudInterval;updateHUD()", 'HUD throttle');
runtime = replaceRequired(runtime, "toastTimer=2.15", "toastTimer=CONFIG.timing.toastDuration", 'toast timing');
runtime = replaceRequired(runtime, "Math.max(35,Math.round((35+elapsed*.32", "Math.max(CONFIG.rewards.minimumPilotXp,Math.round((CONFIG.rewards.minimumPilotXp+elapsed*.32", 'pilot XP floor');
runtime = replaceRequired(runtime, "Math.max(55,Math.round((score*.05+kills*2.1+wave*18+bossesKilled*80+Math.min(180,explorationMax*.025)", "Math.max(CONFIG.rewards.minimumRunCredits,Math.round((score*.05+kills*2.1+wave*18+bossesKilled*80+Math.min(CONFIG.rewards.explorationCreditCap,explorationMax*CONFIG.rewards.explorationCreditFactor)", 'run reward tuning');
runtime = replaceRequired(runtime, "if(save.techPity>=3)", "if(save.techPity>=CONFIG.rewards.techPityRuns)", 'tech pity');
runtime = replaceRequired(runtime, "score+=75", "score+=CONFIG.rewards.discoveryScore", 'discovery score');
runtime = replaceRequired(runtime, "score+=220", "score+=CONFIG.rewards.stationScore", 'station score');
runtime = replaceRequired(runtime, "score+=180", "score+=CONFIG.rewards.asteroidScore", 'asteroid score');
runtime = replaceRequired(runtime, "95+Math.floor(Math.random()*66)", "CONFIG.rewards.stationCreditMin+Math.floor(Math.random()*CONFIG.rewards.stationCreditRange)", 'station credits');
runtime = replaceRequired(runtime, "45+Math.floor(Math.random()*46)", "CONFIG.rewards.asteroidCreditMin+Math.floor(Math.random()*CONFIG.rewards.asteroidCreditRange)", 'asteroid credits');
runtime = replaceRequired(runtime, "visualScale=(W<720||(navigator.hardwareConcurrency&&navigator.hardwareConcurrency<=4))?.65:1", "visualScale=(W<CONFIG.performance.reducedWidth||(navigator.hardwareConcurrency&&navigator.hardwareConcurrency<=CONFIG.performance.lowCoreThreshold))?CONFIG.performance.reducedVisualScale:CONFIG.performance.desktopVisualScale", 'visual scaling');
runtime = replaceRequired(runtime, "window.__SAG11__", "window.__SAG12__", 'debug API namespace');
fs.writeFileSync('sprint12-source.js', runtime);

let html = read(manifest.template);
html = html.replaceAll('Deep Space Refined 0.11', 'Modular Deep Space 0.12');
html = html.replaceAll('DEEP SPACE REFINED 0.11', 'MODULAR DEEP SPACE 0.12');
html = html.replace(/  <link rel="stylesheet" href="sprint05\.css">[\s\S]*?  <link rel="stylesheet" href="sprint11\.css">/, '  <link rel="stylesheet" href="sprint12.bundle.css">');
html = html.replace(/<script src="sprint11-source\.js"><\/script>[\s\S]*?<script src="sprint11-branding\.js"><\/script>/, '<script src="sprint12-config.js"></script>\n<script src="sprint12-source.js"></script>\n<script src="sprint12-ui.js"></script>');
if (!html.includes('sprint12.bundle.css') || !html.includes('sprint12-config.js') || html.includes('sprint10.css')) throw new Error('HTML consolidation failed');
fs.writeFileSync('sprint12.html', html);

console.log(JSON.stringify({
  cssBytes: Buffer.byteLength(css),
  uiBytes: Buffer.byteLength(ui),
  runtimeBytes: Buffer.byteLength(runtime),
  htmlBytes: Buffer.byteLength(html)
}, null, 2));
